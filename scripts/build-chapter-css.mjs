import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assetDirectory = path.join(root, 'public', 'assets', 'css');
const styles = [
    'chapter.css',
    'jci-theme.css',
    'theme-ui.css',
    'project-documents.css',
    'project-workflow.css',
    'dashboard-charts.css',
    'project-tracker.css',
    'project-status.css',
    'task-ui.css',
    'empty-state-ui.css',
    'calendar-ui.css',
    'filter-ui.css',
    'notification-ui.css',
    'overlay-ui.css',
    'navigation-ui.css',
    'workspace-readability.css',
];

const contents = await Promise.all(styles.map(async (name) => {
    const css = await readFile(path.join(assetDirectory, name), 'utf8');
    return `/* ${name} */\n${css.trimEnd()}\n`;
}));

await writeFile(path.join(assetDirectory, 'chapter-bundle.css'),
    `/* Generated by scripts/build-chapter-css.mjs. Edit the source stylesheets instead. */\n${contents.join('\n')}`);

process.stdout.write(`Bundled ${styles.length} chapter stylesheets.\n`);
